-- Entity reference schema + seed data for custom-charges (PostgreSQL).
-- Entity table aligns with com.customcharge.persistencelayer.entities.Entity.
-- Code is the stable unique key; display names may repeat across entities.

-- =========================================
-- COUNTRY / ENTITY TABLES
-- =========================================

CREATE TABLE IF NOT EXISTS country (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    code VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(100) NOT NULL,
    country_id BIGINT NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    tax_value DOUBLE PRECISION,
    "precision" DOUBLE PRECISION,
    CONSTRAINT uq_entity_code UNIQUE (code),
    CONSTRAINT fk_entity_country_id FOREIGN KEY (country_id) REFERENCES country(id)
);

CREATE INDEX IF NOT EXISTS idx_entity_country_id ON entity(country_id);

-- Seed data may contain duplicate display names; code remains the stable unique key.
-- Hibernate may create a random constraint name (e.g. ukmhn0va9i...) on name.
DO $$
DECLARE
    constraint_name TEXT;
BEGIN
    FOR constraint_name IN
        SELECT c.conname
        FROM pg_constraint c
        JOIN pg_class t ON c.conrelid = t.oid
        JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY (c.conkey) AND NOT a.attisdropped
        WHERE t.relname = 'entity'
          AND c.contype = 'u'
          AND array_length(c.conkey, 1) = 1
          AND a.attname = 'name'
    LOOP
        EXECUTE format('ALTER TABLE entity DROP CONSTRAINT IF EXISTS %I', constraint_name);
    END LOOP;
END $$;

ALTER TABLE entity DROP CONSTRAINT IF EXISTS entity_name_key;

