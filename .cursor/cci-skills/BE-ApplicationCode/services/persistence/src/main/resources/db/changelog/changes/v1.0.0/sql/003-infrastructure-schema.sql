-- JaVers SQL repository tables (PostgreSQL, JaVers 7.x).
-- Executed in Liquibase default schema (same as RBAC and JPA entities).

CREATE SEQUENCE IF NOT EXISTS jv_global_id_pk_seq;
CREATE SEQUENCE IF NOT EXISTS jv_commit_pk_seq;
CREATE SEQUENCE IF NOT EXISTS jv_snapshot_pk_seq;

CREATE TABLE IF NOT EXISTS jv_global_id (
    global_id_pk BIGINT NOT NULL DEFAULT nextval('jv_global_id_pk_seq'),
    local_id VARCHAR(191),
    fragment VARCHAR(200),
    type_name VARCHAR(200),
    owner_id_fk BIGINT,
    CONSTRAINT jv_global_id_pk PRIMARY KEY (global_id_pk),
    CONSTRAINT jv_global_id_owner_id_fk FOREIGN KEY (owner_id_fk) REFERENCES jv_global_id (global_id_pk)
);

CREATE INDEX IF NOT EXISTS jv_global_id_local_id_idx ON jv_global_id (local_id);
CREATE INDEX IF NOT EXISTS jv_global_id_owner_id_fk_idx ON jv_global_id (owner_id_fk);

CREATE TABLE IF NOT EXISTS jv_commit (
    commit_pk BIGINT NOT NULL DEFAULT nextval('jv_commit_pk_seq'),
    author VARCHAR(200),
    commit_date TIMESTAMP,
    commit_date_instant VARCHAR(30),
    commit_id NUMERIC(22, 2),
    CONSTRAINT jv_commit_pk PRIMARY KEY (commit_pk)
);

CREATE INDEX IF NOT EXISTS jv_commit_commit_id_idx ON jv_commit (commit_id);

CREATE TABLE IF NOT EXISTS jv_commit_property (
    commit_fk BIGINT NOT NULL,
    property_name VARCHAR(191) NOT NULL,
    property_value VARCHAR(600),
    CONSTRAINT jv_commit_property_pk PRIMARY KEY (commit_fk, property_name),
    CONSTRAINT jv_commit_property_commit_fk FOREIGN KEY (commit_fk) REFERENCES jv_commit (commit_pk)
);

CREATE INDEX IF NOT EXISTS jv_commit_property_commit_fk_idx ON jv_commit_property (commit_fk);
CREATE INDEX IF NOT EXISTS jv_commit_property_property_name_property_value_idx ON jv_commit_property (property_name, property_value);

CREATE TABLE IF NOT EXISTS jv_snapshot (
    snapshot_pk BIGINT NOT NULL DEFAULT nextval('jv_snapshot_pk_seq'),
    type VARCHAR(200),
    version BIGINT,
    state TEXT,
    changed_properties TEXT,
    managed_type VARCHAR(200),
    global_id_fk BIGINT,
    commit_fk BIGINT,
    CONSTRAINT jv_snapshot_pk PRIMARY KEY (snapshot_pk),
    CONSTRAINT jv_snapshot_global_id_fk FOREIGN KEY (global_id_fk) REFERENCES jv_global_id (global_id_pk),
    CONSTRAINT jv_snapshot_commit_fk FOREIGN KEY (commit_fk) REFERENCES jv_commit (commit_pk)
);

CREATE INDEX IF NOT EXISTS jv_snapshot_global_id_fk_idx ON jv_snapshot (global_id_fk);
CREATE INDEX IF NOT EXISTS jv_snapshot_commit_fk_idx ON jv_snapshot (commit_fk);

-- Spring Batch metadata tables (PostgreSQL).
-- Sourced from org/springframework/batch/core/schema-postgresql.sql (Spring Batch 5.x).
-- Executed in Liquibase default schema (same as RBAC and JPA entities).

CREATE TABLE IF NOT EXISTS BATCH_JOB_INSTANCE (
    JOB_INSTANCE_ID BIGINT NOT NULL PRIMARY KEY,
    VERSION BIGINT,
    JOB_NAME VARCHAR(100) NOT NULL,
    JOB_KEY VARCHAR(32) NOT NULL,
    CONSTRAINT JOB_INST_UN UNIQUE (JOB_NAME, JOB_KEY)
);

CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION (
    JOB_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    VERSION BIGINT,
    JOB_INSTANCE_ID BIGINT NOT NULL,
    CREATE_TIME TIMESTAMP NOT NULL,
    START_TIME TIMESTAMP DEFAULT NULL,
    END_TIME TIMESTAMP DEFAULT NULL,
    STATUS VARCHAR(10),
    EXIT_CODE VARCHAR(2500),
    EXIT_MESSAGE VARCHAR(2500),
    LAST_UPDATED TIMESTAMP,
    CONSTRAINT JOB_INST_EXEC_FK FOREIGN KEY (JOB_INSTANCE_ID)
        REFERENCES BATCH_JOB_INSTANCE (JOB_INSTANCE_ID)
);

CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_PARAMS (
    JOB_EXECUTION_ID BIGINT NOT NULL,
    PARAMETER_NAME VARCHAR(100) NOT NULL,
    PARAMETER_TYPE VARCHAR(100) NOT NULL,
    PARAMETER_VALUE VARCHAR(2500),
    IDENTIFYING CHAR(1) NOT NULL,
    CONSTRAINT JOB_EXEC_PARAMS_FK FOREIGN KEY (JOB_EXECUTION_ID)
        REFERENCES BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION (
    STEP_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    VERSION BIGINT NOT NULL,
    STEP_NAME VARCHAR(100) NOT NULL,
    JOB_EXECUTION_ID BIGINT NOT NULL,
    CREATE_TIME TIMESTAMP NOT NULL,
    START_TIME TIMESTAMP DEFAULT NULL,
    END_TIME TIMESTAMP DEFAULT NULL,
    STATUS VARCHAR(10),
    COMMIT_COUNT BIGINT,
    READ_COUNT BIGINT,
    FILTER_COUNT BIGINT,
    WRITE_COUNT BIGINT,
    READ_SKIP_COUNT BIGINT,
    WRITE_SKIP_COUNT BIGINT,
    PROCESS_SKIP_COUNT BIGINT,
    ROLLBACK_COUNT BIGINT,
    EXIT_CODE VARCHAR(2500),
    EXIT_MESSAGE VARCHAR(2500),
    LAST_UPDATED TIMESTAMP,
    CONSTRAINT JOB_EXEC_STEP_FK FOREIGN KEY (JOB_EXECUTION_ID)
        REFERENCES BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION_CONTEXT (
    STEP_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    SHORT_CONTEXT VARCHAR(2500) NOT NULL,
    SERIALIZED_CONTEXT TEXT,
    CONSTRAINT STEP_EXEC_CTX_FK FOREIGN KEY (STEP_EXECUTION_ID)
        REFERENCES BATCH_STEP_EXECUTION (STEP_EXECUTION_ID)
);

CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_CONTEXT (
    JOB_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    SHORT_CONTEXT VARCHAR(2500) NOT NULL,
    SERIALIZED_CONTEXT TEXT,
    CONSTRAINT JOB_EXEC_CTX_FK FOREIGN KEY (JOB_EXECUTION_ID)
        REFERENCES BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

CREATE SEQUENCE IF NOT EXISTS BATCH_STEP_EXECUTION_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
CREATE SEQUENCE IF NOT EXISTS BATCH_JOB_EXECUTION_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
CREATE SEQUENCE IF NOT EXISTS BATCH_JOB_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
