INSERT INTO account (
    id,
    created_by,
    updated_by,
    created_time,
    updated_time,
    entity_code,
    account_nature,
    charge_type,
    version
)
SELECT
    gen_random_uuid(),
    'System',
    'System',
    NOW(),
    NOW(),
    e.code,
    'ENTITY_SETTINGS',
    ct.charge_type,
    0
FROM entity e
INNER JOIN new_entity_codes nec ON nec.code = e.code
CROSS JOIN (
    VALUES
        ('ECD'),
        ('DTC'),
        ('DTA'),
        ('ECS'),
        ('DTS'),
        ('EC3'),
        ('DT3')
) AS ct(charge_type)
WHERE e.is_active = TRUE
  AND NOT EXISTS (
      SELECT 1
      FROM account a
      WHERE a.entity_code = e.code
        AND a.account_nature = 'ENTITY_SETTINGS'
        AND a.charge_type = ct.charge_type
  );
